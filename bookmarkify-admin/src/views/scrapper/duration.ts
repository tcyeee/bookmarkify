/**
 * scrapper 相关页面共用的耗时显示格式。
 *
 * 一轮巡检最坏是「单轮上限 × 单条 15s 超时」，毫秒原样显示会出现读不动的七位数。
 * 轮次表格与手动触发确认框都要用同一套格式：确认框写「预计 3m 20s」、表格却写
 * 「200000 ms」的话，事后根本对不上自己刚才看到的那个预估。
 *
 * 失败站点排行里累计的是**几十上百次**失败的总耗时，很容易越过一小时，所以最上面还有
 * 一档小时。没有它，「一个月在这个站点上烧了 4 小时」会显示成「247m 12s」——那个数
 * 恰恰是整个页面最想让人一眼看懂的。
 */
export function formatDuration(ms: number) {
  if (ms < 1000) return `${ms} ms`;
  if (ms < 60_000) return `${(ms / 1000).toFixed(1)} s`;
  if (ms < 3600_000)
    return `${Math.floor(ms / 60_000)}m ${Math.round((ms % 60_000) / 1000)}s`;
  return `${Math.floor(ms / 3600_000)}h ${Math.round((ms % 3600_000) / 60_000)}m`;
}
