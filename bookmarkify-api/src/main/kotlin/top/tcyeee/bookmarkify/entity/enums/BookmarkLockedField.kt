package top.tcyeee.bookmarkify.entity.enums

/**
 * 被管理员手工锁定、不允许自动抓取覆盖的字段。
 *
 * 存在的理由：内容定期重抓一旦开启，管理员手工修过的标题就会在下一个刷新周期被静默覆盖。
 * 此前唯一的保护是 `verifyFlag`，但它太粗——那是「整条记录人工确认、彻底停止抓取」的开关，
 * 用它来保住一个标题，连图标的刷新也一起停掉了。
 *
 * 语义只有两条：
 * - **手工编辑**该字段 → 加锁；
 * - **显式接受抓取值**（后台「一键更新」/「应用重新获取」）→ 解锁，因为此后它不再是人工值。
 *
 * 自动抓取链路只能读锁、不能改锁。
 */
enum class BookmarkLockedField {
    TITLE,
    DESCRIPTION,
    APP_NAME,
}
