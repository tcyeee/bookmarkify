package top.tcyeee.bookmarkify.server.log

/**
 * **每一张日志表保留多久，以及为什么是这个数。**
 *
 * ## 为什么需要这么一个地方
 *
 * 在这之前只有 `page_ping_log` / `sweep_log` 有清理任务（90 天，常数写在
 * `BookmarkPingLogServiceImpl` 里），另外三张**只增不减**：生产上 `ai_call_log` 的最早一行
 * 就是建表那天（2026-07-31），`scrapper_call_log` 从 2026-08-08、`user_behavior_log`
 * 从 2026-08-18 一行没删过。按当时的量（十几行/天）不构成紧迫问题，但它们都是"写入量随用户数
 * 线性增长、读取只看最近几天"的表 —— 这种表没有保留期就是个定时问题，而且
 * `ai_call_log` 是唯一存**请求/响应原文**的表，它还同时是隐私面。
 *
 * 清理任务已经有一个（凌晨 3 点），把判据集中到这里，而不是让每个 ServiceImpl 各自埋一个常数。
 */
object LogRetention {

    /**
     * scrapper 调用日志：90 天，与活性探测日志同档。
     *
     * 它回答的问题（这个站点最近是不是一直抓不动、失败站点排行）都带时间窗，后台默认看近 7 天；
     * 90 天已经覆盖"上个季度是不是也这样"这类回溯，再久的价值趋近于零。
     */
    const val SCRAPPER_CALL_DAYS = 90L

    /**
     * AI 调用的**原文**：30 天。
     *
     * 原文存在的理由是"模型当时究竟回了什么"这个问题在事后不可复现（见 `AiCallLogEntity`），
     * 而这个问题总是针对**刚刚**产生的那条判定提出的 —— 一个月前某条书签为什么被判成赌博内容，
     * 现实中没有人会去追。于是这里做的是**只清空正文、保留行**：
     * 成功率、耗时、token 消耗这些聚合口径仍然完整（后台的 AI 看板靠它们），
     * 而占掉这张表绝大部分体积、同时也是隐私面的那两列不再无限期留存。
     */
    const val AI_BODY_DAYS = 30L

    /** AI 调用日志整行：1 年。留的是用量与成功率的长期曲线，它们每行只有几十字节 */
    const val AI_ROW_DAYS = 365L

    /**
     * 用户行为审计：1 年。
     *
     * 它回答的是运营/客服问题（"这个人到底有没有导入过书签"），跨度以月计；
     * 比 90 天长，因为用户纠纷往往隔了很久才来。
     */
    const val USER_BEHAVIOR_DAYS = 365L

    /**
     * 后台操作审计：2 年，全系统最长。
     *
     * 这是唯一一张记录"谁动了什么"的表，而它的使用场景天生是事后追溯 —— 一条被删掉的页面、
     * 一个被下架的分享，提出疑问的时间与动作发生的时间可以差很远。它的写入量又是最小的
     * （后台只有运营自己在用），留久一点几乎没有成本。
     */
    const val ADMIN_ACTION_DAYS = 730L
}
